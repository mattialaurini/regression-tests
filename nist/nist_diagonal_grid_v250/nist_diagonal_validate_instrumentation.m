function nist_diagonal_validate_instrumentation(root)
% Prove that the counting-only clone restores to the frozen numerical core.
text=fileread(fullfile(root,'solve_nist_bnb_diagonal_counted.m'));
text=one(text,'function result = solve_nist_bnb_diagonal_counted(problem,options)','function result = solve_nist_bnb_tolerance_study(problem,options)');
text=one(text,strjoin({'assert(options.InitialApproxGridPoints==options.MaximumFineGridPoints, ...'; ...
    '    "This instrumented entry point is restricted to M=Nhat.");'; ...
    ''},newline),'');
text=one(text,strjoin({'[node,stats]=localMarkM1(node,stats);'; ...
    '        t=tic; m1='},newline),'t=tic; m1=');
text=one(text,strjoin({'            [node,stats]=localMarkM1(node,stats);'; ...
    '            t=tic;'; ...
    '            m1='},newline),strjoin({'            t=tic;'; ...
    '            m1='},newline));
text=one(text,strjoin({'stats.nodesWithoutM1=stats.nodesVisited-stats.nodesWithM1;'; ...
    'assert(stats.nodesWithM1>=0 && stats.nodesWithoutM1>=0);'; ...
    ''},newline),'');
text=one(text,'stats=struct("nodesWithM1",0,"nodesWithoutM1",0,"nodesProcessed",0,','stats=struct("nodesProcessed",0,');
text=one(text,'"visitedOnce",false,"didRunM1",false, ...','"visitedOnce",false, ...');
text=one(text,strjoin({''; ...
    'function [node,stats]=localMarkM1(node,stats)'; ...
    'if ~node.didRunM1'; ...
    '    node.didRunM1=true;'; ...
    '    stats.nodesWithM1=stats.nodesWithM1+1;'; ...
    'end'; ...
    'end'; ...
    ''},newline),'');
expected=fileread(fullfile(root,'solve_nist_bnb_tolerance_study.m'));
assert(strcmp(normalize(text),normalize(expected)),'Counted solver differs beyond the declared counters.');
actual=fileread(which('solve_nist_bnb_diagonal_counted'));
assert(strcmp(normalize(actual),normalize(fileread(fullfile(root,'solve_nist_bnb_diagonal_counted.m')))), ...
    'MATLAB path shadows the counted solver.');
end
function text=one(text,old,new)
assert(numel(strfind(text,old))==1,'Instrumentation proof pattern changed.');
text=strrep(text,old,new);
end
function t=normalize(t)
t=strtrim(strrep(t,sprintf('\r\n'),sprintf('\n')));
end
