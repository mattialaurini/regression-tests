function paper_ml_outputs(matfile, outdir)
%PAPER_ML_OUTPUTS Table and text numbers of the certified ML experiment for the paper.
%   paper_ml_outputs                     reads results/tests_ml.mat, writes into '.'
%   paper_ml_outputs(matfile, outdir)    outdir = folder of the paper (the manuscript)
%
%   Writes (from the results of PAPER_TESTS_ML):
%     outdir/Tables/tab_ml_results.tex  per noise level, model and configuration:
%                                       converged runs, median and 90th percentile of
%                                       time, errors in gamma and Emax, NRMSE of the
%                                       concentration
%     outdir/Tables/ml_numbers.tex      \newcommand macros quoted in the text, e.g.
%                                       \MLGammaDPLow (double pole, lowest sigma),
%                                       \MLEmaxOCHigh (one compartment, highest sigma),
%                                       \MLScrRatioDP (median time ratio with/without
%                                       screening), \MLNruns, \MLNconverged, \MLTimeH.
%   Model tags: doublepole -> DP, onecomp -> OC, firstorder -> FO. Medians and
%   times refer to the configuration without screening. The paper loads the files
%   only if they exist, so it compiles also before the ML experiment is run.
if nargin < 1 || isempty(matfile), matfile = fullfile('results', 'tests_ml.mat'); end
if nargin < 2 || isempty(outdir), outdir = '.'; end
S = load(matfile); T = S.T; cfg = S.cfg; st = S.settings_ml;
tabdir = fullfile(outdir, 'Tables'); if ~exist(tabdir, 'dir'), mkdir(tabdir); end
q = @(x, p) paper_prctile(x, p);
models = cfg.models; sig = unique(T.sigma)';
if any(abs(sig - 0.1) < 1e-12), sl = 0.1; else, sl = min(sig(sig > 0)); end
if isempty(sl), sl = min(sig); end
sh = max(sig);
tag = containers.Map({'doublepole', 'onecomp', 'firstorder'}, {'DP', 'OC', 'FO'});
name = containers.Map({'doublepole', 'onecomp', 'firstorder'}, {'double pole', 'one compartment', 'first order'});
NMN = paper_setting_nmn(st);
scr = cellfun(@(c) any(cellfun(@(x) isequal(x, true), c(2:2:end))), st(:, 2));
sNS = find(~scr, 1); if isempty(sNS), sNS = 1; end
sS = find(scr, 1);
npat = numel(unique(T.id));

%% ---- table
L = {'\begin{table}[tb]', ...
    ['\caption{Certified maximum-likelihood identification (', sprintf('%d', npat), ...
     ' patients, PK parameters perturbed with $\omega=', num(cfg.omega), '$): converged runs, ', ...
     'median and 90th percentile of the computation time, of the relative errors in $\gamma$ and ', ...
     '$E_{\max}$, and of the normalized RMS error of the identified concentration, without ', ...
     'screening (', cfgtxt(NMN, scr, false), ') and with screening (', cfgtxt(NMN, scr, true), ')}'], ...
    '\label{tab:ml_results}', '\centering', '\small', '\setlength{\tabcolsep}{2.5pt}', ...
    '\begin{tabular}{cll c rr rr rr rr}', '\toprule', ...
    ['$\sigma$ & model & scr. & conv. & \multicolumn{2}{c}{time [s]} & ', ...
     '\multicolumn{2}{c}{$e_\gamma$ [\%]} & \multicolumn{2}{c}{$e_{E_{\max}}$ [\%]} & ', ...
     '\multicolumn{2}{c}{NRMSE $c$ [\%]} \\'], ...
    ' & & & & med & 90\% & med & 90\% & med & 90\% & med & 90\% \\', '\midrule'};
for a = 1:numel(sig)
    first = true;
    for m = 1:numel(models)
        for s = 1:size(st, 1)
            sel = T.sigma == sig(a) & T.order == m & T.setting == s;
            if ~any(sel), continue; end
            if first, lab = num(sig(a)); first = false; else, lab = ''; end
            if s == 1, mn = name(models{m}); else, mn = ''; end
            if scr(s), yn = 'yes'; else, yn = 'no'; end
            L{end+1} = sprintf('%s & %s & %s & %d/%d & %.0f & %.0f & %.1f & %.1f & %.1f & %.1f & %.1f & %.1f \\\\', ...
                lab, mn, yn, sum(T.converged(sel)), sum(sel), q(T.time(sel), 50), q(T.time(sel), 90), ...
                100*q(T.err_gamma(sel), 50), 100*q(T.err_gamma(sel), 90), 100*q(T.err_Emax(sel), 50), ...
                100*q(T.err_Emax(sel), 90), 100*q(T.nrmse_c(sel), 50), 100*q(T.nrmse_c(sel), 90));
        end
    end
    if a < numel(sig), L{end+1} = '\midrule'; end
end
L = [L, {'\bottomrule', '\end{tabular}', '\end{table}'}];
writelines_(fullfile(tabdir, 'tab_ml_results.tex'), L);

%% ---- macros
M = {'% generated by paper_ml_outputs.m: do not edit'};
add = @(n, v) sprintf('\\newcommand{\\%s}{%s}', n, v);
M{end+1} = add('MLNruns', sprintf('%d', numel(T.id)));
M{end+1} = add('MLNconverged', sprintf('%d', sum(T.converged)));
M{end+1} = add('MLTimeH', sprintf('%.1f', sum(T.time) / 3600));
M{end+1} = add('MLTimeout', num(cfg.timeout));
lev = {sl, 'Low'; sh, 'High'};
for m = 1:numel(models)
    tg = tag(models{m});
    for a = 1:2
        sel = T.order == m & T.sigma == lev{a, 1} & T.setting == sNS;
        if ~any(sel), continue; end
        M{end+1} = add(['MLGamma' tg lev{a, 2}], sprintf('%.1f', 100 * q(T.err_gamma(sel), 50)));
        M{end+1} = add(['MLEmax' tg lev{a, 2}], sprintf('%.1f', 100 * q(T.err_Emax(sel), 50)));
        M{end+1} = add(['MLConc' tg lev{a, 2}], sprintf('%.1f', 100 * q(T.nrmse_c(sel), 50)));
        M{end+1} = add(['MLTime' tg lev{a, 2}], sprintf('%.0f', q(T.time(sel), 50)));
        M{end+1} = add(['MLConv' tg lev{a, 2}], sprintf('%d', sum(T.converged(sel))));
    end
    if ~isempty(sS)
        r = [];
        for sg = sig
            A = T.order == m & T.sigma == sg & T.setting == sNS; B = T.order == m & T.sigma == sg & T.setting == sS;
            [~, ia, ib] = intersect(T.id(A), T.id(B)); ta = T.time(A); tb = T.time(B);
            r = [r; tb(ib) ./ ta(ia)];
        end
        if ~isempty(r)
            M{end+1} = add(['MLScrRatio' tg], sprintf('%.2f', q(r, 50)));
            M{end+1} = add(['MLScrFaster' tg], sprintf('%d', sum(r < 1)));
            M{end+1} = add(['MLScrPairs' tg], sprintf('%d', numel(r)));
        end
    end
end
ab = 1e-7; if isfield(cfg, 'Abstol'), ab = cfg.Abstol; end
M{end+1} = add('MLAbstol', tol_tex(ab));
% runs that did not converge: what they have in common (factual)
nu = find(~T.converged);
if isempty(nu), us = '';
else
    mnames = {'double-pole', 'one-compartment'}; mods = unique(T.order(nu))';
    scrm = cellfun(@(c) any(cellfun(@(x) isequal(x, true), c(2:2:end))), st(:, 2));
    sn = unique(scrm(T.setting(nu)))';
    wds = {'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve'};
    if numel(nu) == 1, us = 'The run that reached the time limit';
    elseif numel(nu) <= 12, us = sprintf('The %s runs that reached the time limit', wds{numel(nu) - 1});
    else, us = sprintf('The %d runs that reached the time limit', numel(nu)); end
    if numel(mods) == 1, us = sprintf('%s used the %s model', us, mnames{mods}); else, us = [us ' used both models']; end
    if isequal(sn, false), us = [us ' without screening']; elseif isequal(sn, true), us = [us ' with screening']; end
    cs_u = arrayfun(@(x) num(x), unique(T.sigma(nu))', 'UniformOutput', false);
    if numel(cs_u) == 1, sgs = sprintf('$\\sigma=%s$', cs_u{1}); else, sgs = sprintf('$\\sigma\\in\\{%s\\}$', strjoin(cs_u, ',\\,')); end
    us = sprintf('%s, with %s; the same cases converged with the other configuration.', us, sgs);
    % check the last claim; drop it if false
    okc = true;
    for r = nu(:)'
        alt = T.order == T.order(r) & T.id == T.id(r) & T.sigma == T.sigma(r) & T.setting ~= T.setting(r);
        if ~any(alt & T.converged == 1), okc = false; end
    end
    if ~okc, us = strrep(us, '; the same cases converged with the other configuration.', '.'); end
end
M{end+1} = add('MLUnconvSentence', us);
M{end+1} = add('MLExecSentence', exec_sentence(cfg));
M{end+1} = add('MLSolverSentence', solver_sentence(cfg));
% baseline E0: estimated (median absolute error, BIS units) or fixed
est = isfield(cfg, 'estimate_e0') && cfg.estimate_e0 && isfield(T, 'err_E0');
if est
    names = {'double-pole', 'one-compartment'}; mods = intersect(unique(T.order)', [1 2]);
    parts = {};
    for x = unique([sl, sh])
        v = arrayfun(@(m) sprintf('%.2f', q(T.err_E0(T.order == m & T.sigma == x), 50)), mods, 'UniformOutput', false);
        if isempty(parts), u = ' BIS units'; else, u = ''; end
        parts{end+1} = sprintf('%s%s for $\\sigma=%s$', strjoin(v, ' and '), u, num(x));
    end
    if numel(mods) == 2, mn = 'double-pole and one-compartment models'; else, mn = [names{mods} ' model']; end
    e0s = sprintf(['The baseline $E_0$ was estimated together with $E_{\\max}$; its median absolute error ', ...
        'is %s (%s).'], strjoin(parts, ', and '), mn);
else
    e0s = 'In these runs the baseline $E_0$ was fixed to its true value.';
end
M{end+1} = add('MLEZeroSentence', e0s);
writelines_(fullfile(tabdir, 'ml_numbers.tex'), M);
fprintf('Written: %s, %s\n', fullfile(tabdir, 'tab_ml_results.tex'), fullfile(tabdir, 'ml_numbers.tex'));
end

function s = cfgtxt(NMN, scr, which)
i = find(scr == which, 1);
if isempty(i), s = 'not run'; else, s = sprintf('$(N,M,\\widehat N)=(%d,%d,%d)$', NMN(i, :)); end
end

function s = num(x)
s = sprintf('%g', x);
end

function writelines_(file, L)
fid = fopen(file, 'w'); fprintf(fid, '%s\n', L{:}); fclose(fid);
end

function s = exec_sentence(cfg)
% how the runs were executed (for the text of the paper)
s = exec_sentence0(cfg);
if isfield(cfg, 'gurobi_presolve') && cfg.gurobi_presolve == 0
    s = [s(1:end-1), ' and its presolve disabled.'];
end
end

function s = exec_sentence0(cfg)
if isfield(cfg, 'parallel') && isequal(cfg.parallel, true)
    s = 'The runs were executed in parallel, one per core, with one Gurobi thread each.';
else
    th = 0; if isfield(cfg, 'gurobi_threads'), th = cfg.gurobi_threads; end
    if th == 0
        s = 'The runs were executed one after another, with the automatic multi-threading of Gurobi.';
    elseif th == 1
        s = 'The runs were executed one after another, with one Gurobi thread.';
    else
        s = sprintf('The runs were executed one after another, with %d Gurobi threads.', th);
    end
end
end

function s = solver_sentence(cfg)
% how the bound subproblems were solved (for the text of the paper)
mode = 'gurobi'; if isfield(cfg, 'qp_solver'), mode = cfg.qp_solver; end
if strcmp(mode, 'hybrid')
    s = ['Each bound subproblem is first solved approximately by an accelerated ', ...
         'projected-gradient method applied to the problem ', ...
         '\[\min_{v\in\Delta^{r(N)-1}}\;\sum_i\max\{0,\,((G_N+C^-)v)_i,\,-((G_N+C^+)v)_i\}^2,\]', ...
         'which is equivalent to~\eqref{eqn_bnd_m1} with the 2-norm ($C^-$ and $C^+$ collect ', ...
         'the coefficients $c^-_{i,j}$ and $c^+_{i,j}$, and the error vector $e$ is eliminated ', ...
         'row by row); its weak-duality bound and its objective value bracket the optimal value ', ...
         'of the subproblem, and Gurobi is called only when this bracket does not decide the ', ...
         'pruning test. The upper-bound subproblems are solved by the projected-gradient method alone.'];
else
    s = 'All the bound subproblems were solved with Gurobi.';
end
end

function s = tol_tex(x)
% tolerance as TeX: 10^{k} for powers of ten, otherwise %g
k = round(log10(x));
if abs(x - 10^k) <= 1e-12 * x, s = sprintf('10^{%d}', k); else, s = sprintf('%g', x); end
end
